#!/usr/bin/env node
// Parity watch. Compares the tools this fork registers against the reference list and writes docs/PARITY.md.
//   reference = Meta's official MCP (https://mcp.facebook.com/ads tools/list) when META_OFFICIAL_MCP_TOKEN is set
//               (available after ads_mcp_management approval), else upstream byadsco `main` (git fetch upstream).
// Exit 1 when the reference has a tool we do not cover. "Covered" = same name registered here, or a row in
// docs/official-parity.md that maps it to a tool registered here. Official tools already listed there as
// pending/partial are shown but do not fail the run; unknown ones do.
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const NAME = /registerTool\(\s*"([a-z0-9_]+)"/g;
const names = (text) => [...text.matchAll(NAME)].map((m) => m[1]);
const git = (...a) => execFileSync("git", a, { cwd: root, encoding: "utf8", maxBuffer: 64 << 20 });

function oursFromTree() {
  const dir = join(root, "src/tools");
  return readdirSync(dir).filter((f) => f.endsWith(".ts")).flatMap((f) => names(readFileSync(join(dir, f), "utf8")));
}

function upstreamTools() {
  git("fetch", "--quiet", "upstream", "main");
  const files = git("ls-tree", "-r", "--name-only", "upstream/main", "src/tools").split("\n").filter((f) => f.endsWith(".ts"));
  return files.flatMap((f) => names(git("show", `upstream/main:${f}`)));
}

async function officialTools(token) {
  const call = async (body, session) => {
    const res = await fetch("https://mcp.facebook.com/ads", {
      method: "POST",
      headers: {
        authorization: `Bearer ${token}`,
        "content-type": "application/json",
        accept: "application/json, text/event-stream",
        ...(session ? { "mcp-session-id": session } : {}),
      },
      body: JSON.stringify(body),
    });
    if (!res.ok) throw new Error(`official MCP HTTP ${res.status}`);
    const text = await res.text();
    const data = text.split("\n").find((l) => l.startsWith("data:"));
    return { json: JSON.parse(data ? data.slice(5) : text), session: res.headers.get("mcp-session-id") };
  };
  const init = await call({ jsonrpc: "2.0", id: 1, method: "initialize", params: { protocolVersion: "2025-03-26", capabilities: {}, clientInfo: { name: "parity", version: "1" } } });
  const list = await call({ jsonrpc: "2.0", id: 2, method: "tools/list", params: {} }, init.session);
  return list.json.result.tools.map((t) => t.name);
}

function parityTable() {
  const rows = new Map();
  for (const line of readFileSync(join(root, "docs/official-parity.md"), "utf8").split("\n")) {
    const m = line.match(/^\| `([a-z0-9_]+)` \| `([a-z0-9_]+)` \| ([^|]+) \|$/);
    if (m) rows.set(m[1], { here: m[2], status: m[3].trim() });
  }
  return rows;
}

const token = process.env.META_OFFICIAL_MCP_TOKEN?.trim();
const ours = new Set(oursFromTree());
const table = parityTable();
let source, reference;
if (token) { source = "Meta official MCP (mcp.facebook.com/ads)"; reference = new Set(await officialTools(token)); }
else { source = `upstream byadsco/meta-ads-mcp main @ ${git("rev-parse", "--short", "upstream/main").trim() || "?"}`; reference = new Set(upstreamTools()); }

const covered = (t) => ours.has(t) || (table.has(t) && ours.has(table.get(t).here));
const both = [...reference].filter(covered).sort();
const referenceOnly = [...reference].filter((t) => !covered(t)).sort();
const known = referenceOnly.filter((t) => table.has(t));
const unknown = referenceOnly.filter((t) => !table.has(t));
const mapped = new Set([...reference].map((t) => (ours.has(t) ? t : table.get(t)?.here)).filter(Boolean));
const oursOnly = [...ours].filter((t) => !mapped.has(t)).sort();

const when = new Intl.DateTimeFormat("en-US", { timeZone: "America/New_York", dateStyle: "medium", timeStyle: "short" }).format(new Date());
const list = (a) => (a.length ? a.map((t) => `- \`${t}\``).join("\n") : "- none");
const md = `# Parity watch

Generated by \`scripts/parity.mjs\` on ${when} ET. Reference: ${source}.

| | Count |
|---|---|
| Both (covered here) | ${both.length} |
| Reference-only, not in \`docs/official-parity.md\` (fails the run) | ${unknown.length} |
| Reference-only, already tracked as pending or partial | ${known.length} |
| Ours-only (fork or upstream extras) | ${oursOnly.length} |

## Reference-only, new
${list(unknown)}

## Reference-only, tracked in docs/official-parity.md
${list(known)}

## Ours-only
${list(oursOnly)}

## Both
${list(both)}
`;
writeFileSync(join(root, "docs/PARITY.md"), md);
console.log(`parity: ${both.length} both, ${unknown.length} new reference-only, ${known.length} tracked, ${oursOnly.length} ours-only (reference: ${source}; ours ${ours.size})`);
process.exit(unknown.length ? 1 : 0);
